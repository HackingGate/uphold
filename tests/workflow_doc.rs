//! `docs/workflow.md`: how an action reaches uphold, and which bundled rules
//! fire where. Generated here and committed, so a reader on GitHub sees it and
//! a change to a bundled set cannot leave it describing the old tool.
//!
//! The tables come from the binary's own output, never from this file: which
//! rules exist and what they say from `rules --sets --json`, and where each one
//! runs from `rules --effective --json` over a scratch repository that
//! inherits every set. The second is asked rather than re-derived because the
//! answer depends on the rule's kind, on `seams` and on which built-ins judge
//! text (`Rule::seams`), and a copy of that logic here would be a reader free
//! to disagree with the engine.
//!
//! The diagram and the prose around it are code structure, so they are
//! constants below. Nothing in any JSON output names an entry point.
//!
//! `UPHOLD_WORKFLOW_GOLDEN=bless cargo test --test workflow_doc` rewrites the
//! file; without it a difference fails the test.

#![expect(
    clippy::expect_used,
    clippy::let_underscore_must_use,
    clippy::tests_outside_test_module,
    reason = "A test asserts on the outcome; a panic in the harness IS the failure report, and there is no caller to hand a Result to"
)]

mod support;

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use serde_json::Value;

const BLESS: &str = "UPHOLD_WORKFLOW_GOLDEN";

/// The diagram and the prose that frame the tables. Entry points are code
/// structure that no JSON output carries, so they are written here and the
/// tests that drive each caller are what keep them honest.
const HEADER: &str = "\
<!-- Generated by tests/workflow_doc.rs; do not edit by hand.
     Regenerate: UPHOLD_WORKFLOW_GOLDEN=bless cargo test --test workflow_doc -->

# How an action reaches uphold

Every path into uphold ends in one of a few commands. This page maps each way
in to the command it ends in, then lists the bundled rules that fire there.
It describes the tool; a repository's own rules are in its policy file, and
`uphold rules --effective` lists what one resolves to.

```mermaid
flowchart LR
    commit[git commit] --> hooks[pre-commit, commit-msg and<br/>pre-merge-commit hooks]
    push[git push] --> prepush[pre-push hook]
    install[uphold hooks --install<br/>or lefthook install] -.writes.-> hooks
    install -.writes.-> prepush
    hooks --> guard_stage[uphold guard --stage STAGE]
    prepush --> guard_push[uphold guard --stage pre-push]
    hooks -. runner config .-> scan
    cmd[git, gh, ... on PATH] --> link[link named after the command]
    shiminstall[uphold shim --install<br/>uphold shim --hook] -.makes and<br/>puts on PATH.-> link
    link --> shim[uphold shim COMMAND]
    shim --> real[the real command]
    shim --> refuse[refusal, exit 1 or 2]
    agent[agent tool call:<br/>Claude Code PreToolUse, Codex] --> hook[uphold hook claude-code or codex]
    hook --> allow[call proceeds]
    hook --> deny[call refused]
    ci[CI or by hand] --> scan[uphold scan]
    ci --> guard_manual[uphold guard --stage manual]
    ci --> supply[uphold supply-chain]
    piped[text piped in] --> text[uphold scan --text<br/>uphold guard --text]
```

- **Git stages.** `uphold hooks --install` writes `pre-commit`, `commit-msg`,
  `pre-merge-commit` and `pre-push` as tracked files and points
  `core.hooksPath` at them; it refuses lefthook, which installs and owns its
  own hooks from the config `uphold init --lefthook` writes. Either way the
  stage ends in `uphold guard --stage STAGE`. A runner's config may also run
  `uphold scan` or `uphold supply-chain --staged` at `pre-commit`; those are
  the repository's choice, not the hook's.
- **Shim.** A link named for the command, on PATH ahead of the real one.
  `uphold shim --install` makes the links and `uphold shim --hook` keeps them
  on PATH only inside a tree that declares a policy. With no `[[shim]]` for the
  command, the real command runs untouched.
- **Agent harness.** `uphold hook` judges a pending tool call read on stdin. It
  exists for publishing that spawns no process, such as an MCP server, so it
  is configured for those tools rather than for shell commands.
- **CI and manual.** `uphold scan` reads the tree, `uphold guard --stage
  manual` runs the guards that sweep the whole repository, and `uphold
  supply-chain` runs the dependency and secret scanners.
- **Text.** `uphold scan --text` and `uphold guard --text` judge text with no
  path, such as a commit message.

";

/// What each caller is, in the order the tables follow, and the seam name
/// `rules --effective --json` uses for it. A git stage is a `git_hooks` entry
/// and not a seam, so it carries no seam name.
struct Caller {
    heading: &'static str,
    note: &'static str,
    stage: Option<&'static str>,
    seam: Option<&'static str>,
}

const CALLERS: [Caller; 9] = [
    Caller {
        heading: "commit-msg",
        note: "`uphold guard --stage commit-msg`, after `git commit` writes the message.",
        stage: Some("commit-msg"),
        seam: None,
    },
    Caller {
        heading: "pre-commit",
        note: "`uphold guard --stage pre-commit`, over what is staged.",
        stage: Some("pre-commit"),
        seam: None,
    },
    Caller {
        heading: "pre-merge-commit",
        note: "`uphold guard --stage pre-merge-commit`, when a merge is about to commit.",
        stage: Some("pre-merge-commit"),
        seam: None,
    },
    Caller {
        heading: "pre-push",
        note: "`uphold guard --stage pre-push`, over the range being pushed.",
        stage: Some("pre-push"),
        seam: None,
    },
    Caller {
        heading: "manual",
        note: "`uphold guard --stage manual`, from CI or by hand.",
        stage: Some("manual"),
        seam: None,
    },
    Caller {
        heading: "shim",
        note: "`uphold shim COMMAND`, in front of a command that publishes.",
        stage: None,
        seam: Some("shim"),
    },
    Caller {
        heading: "agent hook",
        note: "`uphold hook claude-code` and `uphold hook codex`.",
        stage: None,
        seam: Some("hook"),
    },
    Caller {
        heading: "text",
        note: "`uphold scan --text` and `uphold guard --text`.",
        stage: None,
        seam: Some("text"),
    },
    Caller {
        heading: "scan",
        note: "`uphold scan`, over the tree. A rule that reads files and has no \
               git hook or published-text seam runs only here.",
        stage: None,
        seam: Some("scan"),
    },
];

fn uphold(directory: &Path, args: &[&str]) -> Value {
    let output = Command::new(env!("CARGO_BIN_EXE_uphold"))
        .args(args)
        .current_dir(directory)
        .env("XDG_CONFIG_HOME", directory.with_extension("xdg"))
        .env_remove("UPHOLD_ALLOW")
        .stdin(Stdio::null())
        .output()
        .expect("the binary runs");
    assert!(
        output.status.success(),
        "uphold {args:?} exited {:?}: {}",
        output.status.code(),
        String::from_utf8_lossy(&output.stderr),
    );
    serde_json::from_slice(&output.stdout).expect("the output is JSON")
}

/// A repository that inherits every bundled set, for `rules --effective`.
///
/// A policy loads only if each command a rule stands in front of has a
/// `[[shim]]`, so one is declared per leading word the sets name.
fn every_set_repository(sets: &[Value]) -> PathBuf {
    let root = support::scratch("workflow-doc");
    std::fs::create_dir_all(root.join("policy")).expect("fixture directory");
    support::git(&root, &["init", "-q", "-b", "main"]);

    let names: Vec<String> = sets
        .iter()
        .map(|set| format!("{:?}", text(&set["set"])))
        .collect();
    let mut commands: Vec<&str> = sets
        .iter()
        .flat_map(|set| set["commands"].as_array().into_iter().flatten())
        .filter_map(|command| text(command).split_whitespace().next())
        .collect();
    commands.sort_unstable();
    commands.dedup();

    let mut policy = format!(
        "owner = \"example\"\nvisibility = \"public\"\n[inherit]\nsets = [{}]\n",
        names.join(", ")
    );
    for command in commands {
        let _ = writeln!(policy, "[[shim]]\ncommand = {command:?}");
    }
    std::fs::write(root.join("policy/principles.toml"), policy).expect("policy");
    root
}

fn text(value: &Value) -> &str {
    value.as_str().expect("a string")
}

/// The first sentence of a message, on one line and safe in a table cell.
fn first_sentence(message: &str) -> String {
    let flat = message.split_whitespace().collect::<Vec<_>>().join(" ");
    let end = flat
        .match_indices(". ")
        .next()
        .map_or(flat.len(), |(at, _)| at + 1);
    flat[..end].replace('|', "\\|")
}

/// What a table cell says for a rule. A built-in guard declares no message: it
/// composes its report from what it found, so the cell says that instead of
/// standing empty.
fn message_cell(rule: &Value) -> String {
    let builtin = rule["builtin"]
        .as_str()
        .map(|name| format!("The `{name}` guard writes its own report."));
    rule["message"]
        .as_str()
        .filter(|message| !message.is_empty())
        .map(first_sentence)
        .or(builtin)
        .unwrap_or_default()
}

fn render() -> String {
    let sets_dir = support::scratch("workflow-doc-sets");
    std::fs::create_dir_all(&sets_dir).expect("fixture directory");
    let sets = uphold(&sets_dir, &["rules", "--sets", "--json"]);
    let sets = sets.as_array().expect("an array of sets");

    let root = every_set_repository(sets);
    let effective = uphold(&root, &["rules", "--effective", "--json"]);
    let mut resolved: BTreeMap<&str, &Value> = BTreeMap::new();
    for rule in effective.as_array().expect("an array of rules") {
        assert!(
            resolved.insert(text(&rule["id"]), rule).is_none(),
            "two bundled rules share the id {}; the tables key on it",
            rule["id"]
        );
    }

    let mut out = String::from(HEADER);
    for caller in &CALLERS {
        let mut rows = String::new();
        for set in sets {
            for rule in set["rules"].as_array().expect("an array of rules") {
                let id = text(&rule["id"]);
                let found = resolved
                    .get(id)
                    .expect("every set rule is in the effective list");
                let hooks = found["git_hooks"].as_array().expect("git_hooks");
                let seams = found["seams"].as_array().expect("seams");
                let fires = match (caller.stage, caller.seam) {
                    (Some(stage), _) => hooks.iter().any(|hook| text(hook) == stage),
                    (None, Some(seam)) => seams.iter().any(|name| text(name) == seam),
                    (None, None) => false,
                };
                if fires {
                    let _ = writeln!(
                        rows,
                        "| `{id}` | `{}` | {} |",
                        text(&set["set"]),
                        message_cell(rule)
                    );
                }
            }
        }
        let _ = write!(out, "## {}\n\n{}\n\n", caller.heading, caller.note);
        if rows.is_empty() {
            out.push_str("No bundled rule fires here.\n\n");
        } else {
            out.push_str("| Rule | Set | Message |\n|---|---|---|\n");
            out.push_str(&rows);
            out.push('\n');
        }
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

#[test]
fn the_workflow_doc_is_what_the_binary_says() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("docs/workflow.md");
    let rendered = render();

    if std::env::var(BLESS).is_ok_and(|mode| mode == "bless") {
        std::fs::write(&path, &rendered).expect("write docs/workflow.md");
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == rendered,
        "docs/workflow.md is stale; regenerate it with `{BLESS}=bless cargo test --test workflow_doc`"
    );
}
